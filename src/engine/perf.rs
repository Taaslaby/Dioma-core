//! Purpose:     низкоуровневые оптимизации численного ядра
//! Description: STDP-следы затухают экспоненциально (×0.975 за шаг); за
//!              тысячи тиков они уходят в денормальный диапазон (< 1.2e-38),
//!              и SIMD-арифметика на них замедляется в ~10 раз (классический
//!              денормальный штраф, найден аудитом examples/speed_audit).
//!              Включаем FTZ (flush-to-zero): денормальные РЕЗУЛЬТАТЫ операций
//!              сбрасываются в ноль — стандарт игровых движков (Unity/Unreal).
//!              Для динамики существа значения < 1e-38 — чистый шум.
//!
//! ⚠ Только FTZ, БЕЗ DAZ: pillars-runner детектирует спайки реинтерпретацией
//! i32→f32 (1 → денормаль 1.4e-45) и сравнением `> 0.0`; DAZ (denormals-are-
//! zero) обнуляет ВХОДЫ сравнений → спайки перестают детектироваться и мозг
//! «молчит» (см. run_lif_alpha: комментарий про reinterpret + регрессия
//! `organs_reflex_fast_and_cortex_learns`).
//!
//! MXCSR — состояние ПОТОКА, поэтому флаг ставится при каждом создании
//! мозга/сцены (2 инструкции, дёшево): каждый рабочий поток получает его
//! при первом создании Brain/Scene. Многопоточным воркерам достаточно
//! создать мозг на своём потоке (или вызвать `flush_denormals()` вручную).
//! author: Atlasov anton
//! -------------------------------------------------------------------------

/// Добавить FTZ (0x8000) к MXCSR, сохранив маски исключений и округление.
pub fn flush_denormals() {
    #[cfg(target_arch = "x86_64")]
    unsafe {
        use std::arch::asm;
        let mut csr: u32 = 0;
        // stmxcsr пишет по адресу из регистра: `in(reg) &mut csr` даёт
        // валидный адрес (out(reg) оставил бы регистр неинициализиро-
        // ванным → запись в мусор, access violation).
        asm!(
            "stmxcsr [{addr}]",
            addr = in(reg) &mut csr,
            options(nostack, preserves_flags)
        );
        csr |= 0x8000; // FTZ (без DAZ — см. шапку модуля)
        asm!(
            "ldmxcsr [{addr}]",
            addr = in(reg) &csr,
            options(nostack, preserves_flags)
        );
    }
    #[cfg(not(target_arch = "x86_64"))]
    {
        // ARM и прочие: FPCR FZ настраивается иначе — не трогаем.
    }
}
