//! Сцена: «кирпичи» спрайтового конвейера и мировая геометрия.
//!
//! Всё, из чего собирается кадр до эффектов:
//! - [`SpriteAtlas`] — атлас процедурных текстур (круг, кольцо, ягода, бар…),
//! - [`Sprite`] + [`SpriteFx`] — спрайт-инстанс и его визуальный эффект,
//! - [`SpriteBatch`] — общий инстансный батч (сортировка layer/depth на CPU),
//! - [`Flipbook`] — покадровая анимация региона атласа,
//! - [`Tilemap`] / [`TileBatch`] — сетка u16-тайлов поверх обычного батча,
//! - [`Mesh`] / [`MeshBatch`] — произвольная триангулированная геометрия
//!   (CPU-скиннинг: вершины в мировых координатах).
//!
//! Публичные типы реэкспортируются в корне крейта; сами модули доступны как
//! `dioma_render::scene::*` (старые пути `dioma_render::atlas` и т.д. тоже
//! работают — см. алиасы в lib.rs).

pub mod atlas;
pub mod batch;
pub mod flipbook;
pub mod mesh;
pub mod sprite;
pub mod tilemap;
