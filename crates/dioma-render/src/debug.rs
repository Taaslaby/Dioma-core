//! Debug-тулкит: тогглы проходов рендера ([`RenderDebug`]) и пиксельный
//! текстовый оверлей ([`DebugFont`]) — встроенный 8×8 bitmap-шрифт (public
//! domain, классический font8x8 на основе IBM VGA), ни одной зависимости.

use crate::atlas::SpriteAtlas;
use crate::mesh::Mesh;
use wgpu::util::DeviceExt;

/// Тогглы проходов рендера и оверлея.
///
/// Все `draw_*` по умолчанию `true`; `show_overlay` и `wireframe_meshes` —
/// `false`. Поле [`Renderer::debug`](crate::Renderer::debug) публичное:
/// меняйте флаги напрямую между кадрами.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct RenderDebug {
    /// Рисовать базовые спрайты (без эффекта).
    pub draw_sprites: bool,
    /// Рисовать спрайты с эффектами (fx-пайплайны).
    pub draw_fx: bool,
    /// Рисовать меши ([`Renderer::render_meshes`]).
    pub draw_meshes: bool,
    /// Рисовать источники света ([`Renderer::render_lights`]).
    pub draw_lights: bool,
    /// Рисовать частицы ([`Renderer::render_particles`]).
    pub draw_particles: bool,
    /// Показывать текстовый оверлей (решает вызывающий код, каким строкам
    /// наполнять; сам [`Renderer::render_debug_overlay`] не проверяет флаг).
    pub show_overlay: bool,
    /// Рисовать меши каркасом (`PolygonMode::Line`), если бэкенд
    /// поддерживает `POLYGON_MODE_LINE`; иначе флаг игнорируется.
    pub wireframe_meshes: bool,
}

impl Default for RenderDebug {
    fn default() -> Self {
        Self {
            draw_sprites: true,
            draw_fx: true,
            draw_meshes: true,
            draw_lights: true,
            draw_particles: true,
            show_overlay: false,
            wireframe_meshes: false,
        }
    }
}

impl RenderDebug {
    /// Всё включено: все проходы, оверлей, каркас.
    pub fn all_on() -> Self {
        Self {
            draw_sprites: true,
            draw_fx: true,
            draw_meshes: true,
            draw_lights: true,
            draw_particles: true,
            show_overlay: true,
            wireframe_meshes: true,
        }
    }

    /// Всё выключено: ни один проход не рисуется (сцена остаётся пустой),
    /// оверлей и каркас тоже.
    pub fn all_off() -> Self {
        Self {
            draw_sprites: false,
            draw_fx: false,
            draw_meshes: false,
            draw_lights: false,
            draw_particles: false,
            show_overlay: false,
            wireframe_meshes: false,
        }
    }
}

