/// Пиксельный шрифт оверлея: атлас 128×48 (16 столбцов × 6 строк ячеек 8×8)
/// с белыми глифами ASCII 32..=126 + UV-прямоугольники глифов.
///
/// Текстура собирается ОДНИМ RGBA-буфером (без per-глифных записей) через
/// `create_texture_with_data` — один upload на весь атлас.
pub struct DebugFont {
    /// Атлас глифов (можно передавать в меш-проходы напрямую).
    pub atlas: SpriteAtlas,
    /// UV-прямоугольники глифов: индекс = код ASCII − 32 (как у [`FONT_8X8`]).
    glyphs: Vec<[f32; 4]>,
}

/// Сетка глифов в атласе: 16 столбцов × 6 строк ячеек 8×8 → текстура 128×48.
const GRID_COLS: u32 = 16;
const GRID_ROWS: u32 = 6;
const GLYPH_SIZE: u32 = 8;

impl DebugFont {
    /// Создаёт атлас глифов 128×48 (95 глифов ASCII 32..=126) и регистрирует
    /// регионы `glyph_32`..`glyph_126`. Данные копируются одним RGBA-буфером
    /// прямо при создании текстуры (одна запись на весь атлас).
    pub fn new(device: &wgpu::Device, queue: &wgpu::Queue) -> DebugFont {
        let width = GRID_COLS * GLYPH_SIZE;
        let height = GRID_ROWS * GLYPH_SIZE;
        let mut pixels = vec![0u8; (width * height * 4) as usize];
        for (gi, glyph) in FONT_8X8.iter().enumerate() {
            let col = (gi as u32 % GRID_COLS) * GLYPH_SIZE;
            let row = (gi as u32 / GRID_COLS) * GLYPH_SIZE;
            for gy in 0..8 {
                for gx in 0..8 {
                    if glyph[gy] & (1 << gx) != 0 {
                        let px = (col + gx as u32) as usize;
                        let py = (row + gy as u32) as usize;
                        let i = (py * width as usize + px) * 4;
                        pixels[i..i + 4].copy_from_slice(&[255, 255, 255, 255]);
                    }
                }
            }
        }
        let texture = device.create_texture_with_data(
            queue,
            &wgpu::TextureDescriptor {
                label: Some("dioma-render debug font atlas"),
                size: wgpu::Extent3d { width, height, depth_or_array_layers: 1 },
                mip_level_count: 1,
                sample_count: 1,
                dimension: wgpu::TextureDimension::D2,
                format: wgpu::TextureFormat::Rgba8UnormSrgb,
                usage: wgpu::TextureUsages::TEXTURE_BINDING,
                view_formats: &[],
            },
            wgpu::util::TextureDataOrder::LayerMajor,
            &pixels,
        );
        let mut atlas = SpriteAtlas::from_texture(device, texture, width, height);
        let mut glyphs = Vec::with_capacity(FONT_8X8.len());
        for gi in 0..FONT_8X8.len() as u32 {
            let col = gi % GRID_COLS;
            let row = gi / GRID_COLS;
            let uv = [
                (col * GLYPH_SIZE) as f32 / width as f32,
                (row * GLYPH_SIZE) as f32 / height as f32,
                ((col + 1) * GLYPH_SIZE) as f32 / width as f32,
                ((row + 1) * GLYPH_SIZE) as f32 / height as f32,
            ];
            atlas.insert_region(&format!("glyph_{}", gi + 32), uv);
            glyphs.push(uv);
        }
        DebugFont { atlas, glyphs }
    }

    /// UV-прямоугольник глифа `c` в атласе. Символы вне ASCII 32..=126
    /// отображаются на '?'.
    pub fn glyph_uv(&self, c: char) -> [f32; 4] {
        let ascii = c as u32;
        if (32..=126).contains(&ascii) {
            self.glyphs[(ascii - 32) as usize]
        } else {
            self.glyphs[('?' as u32 - 32) as usize]
        }
    }

    /// Меш одной строки текста в ЭКРАННЫХ пикселях.
    ///
    /// `(x, y)` — верхний левый угол строки (Y вниз); каждый видимый глиф —
    /// квад ячейки 8×8, масштабированный на `scale`; шаг колонки (межглифовый
    /// интервал) — `8·scale·0.6` для читаемости. Квады центрируются на ячейке:
    /// `world_x = x − viewport.w/2 + col·advance + 4·scale`,
    /// `world_y = viewport.h/2 − y − 4·scale` (верх экрана = больший Y мира) —
    /// рисуйте камерой `Camera::new(viewport)` (центр 0, зум 1).
    /// Пустые глифы (пробел) занимают шаг, но квад не создают; неизвестные
    /// символы — '?'.
    pub fn text_mesh(
        &self,
        text: &str,
        x: f32,
        y: f32,
        scale: f32,
        color: [f32; 4],
        viewport: [f32; 2],
    ) -> Mesh {
        let advance = 8.0 * scale * 0.6;
        let cell = 8.0 * scale;
        let mut mesh = Mesh { vertices: Vec::new(), indices: Vec::new() };
        for (col, c) in text.chars().enumerate() {
            let gi = ascii_index(c);
            // Пустой глиф (пробел и т.п.): шаг есть, квада нет.
            if FONT_8X8[gi].iter().all(|&b| b == 0) {
                continue;
            }
            let center = [
                x - viewport[0] * 0.5 + col as f32 * advance + 4.0 * scale,
                viewport[1] * 0.5 - y - 4.0 * scale,
            ];
            let quad = Mesh::quad(center, [cell, cell], self.glyphs[gi], color);
            let base = mesh.vertices.len() as u32;
            mesh.vertices.extend_from_slice(&quad.vertices);
            mesh.indices.extend(quad.indices.iter().map(|i| i + base));
        }
        mesh
    }
}

/// Индекс глифа в [`FONT_8X8`] (код ASCII − 32); вне ASCII 32..=126 — '?'.
fn ascii_index(c: char) -> usize {
    let ascii = c as u32;
    if (32..=126).contains(&ascii) {
        (ascii - 32) as usize
    } else {
        ('?' as u32 - 32) as usize
    }
}
